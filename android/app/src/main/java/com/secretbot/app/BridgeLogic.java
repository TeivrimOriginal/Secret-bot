package com.secretbot.app;

/**
 * Логика моста, вынесенная БЕЗ единого импорта android.*.
 *
 * Зачем так: MainActivity целиком не проверить без телефона — там Activity,
 * WebView, Toast. А этот класс — чистый Java, его можно собрать javac и
 * выполнить на обычной машине (android/test-bridge.py так и делает). Ошибки
 * в проверке имени файла и в счёте размера находят тесты, а не юзер после
 * установки.
 *
 * Правило простое: если класс можно проверить без SDK — не заставляем его
 * ждать телефона.
 */
public final class BridgeLogic {

    /**
     * Предел на один файл.
     *
     * Страница отдаёт мосту строку в base64, то есть примерно в 4/3 больше
     * исходника, а Java держит строку в UTF-16 — в памяти это уже ~2.7 от
     * размера файла. Файл в 200 МБ превращается в ~270 МБ символов и ~540 МБ
     * живых байт: WebView с such строкой не справляется, приложение падает.
     *
     * 32 МБ — это примерно 45 МБ символов base64, то есть ~90 МБ в куче.
     * На телефоне с 2 ГБ это переживается, на 512 МБ — впритык, но не смертельно.
     * Файлы больше лимита не «нечаянно ломают приложение», а получают внятную
     * ошибку; большие файлы надо передавать по частям.
     */
    public static final int MAX_BYTES = 32 * 1024 * 1024;

    /** Примерная длина строки base64, с которой начинается отказ. */
    private static String humanSize(long bytes) {
        if (bytes < 1024 * 1024) {
            return (bytes / 1024) + " КБ";
        }
        return (bytes / (1024 * 1024)) + " МБ";
    }

    private BridgeLogic() {
    }

    /**
     * Имя файла, безопасное для каталога.
     *
     * Разделители пути заменяются на подчёркивание, поэтому выйти из каталога
     * нельзя: «../../secret» превращается в «.._.._secret», а это обычный
     * файл внутри каталога. Точки и пробелы оставляем — они встречаются в
     * обычных именах («отчёт 2026.pdf»), а для обхода каталога всё равно
     * нужен разделитель, которого тут уже нет.
     */
    public static String safeName(String name) {
        String clean = name == null ? "" : name.trim();
        clean = clean.replaceAll("[\\\\/:*?\"<>|\\u0000-\\u001f]", "_");
        if (clean.isEmpty() || isDotsOnly(clean)) {
            // Пустое имя и варианты из одних точек («.», «..») — плохие имена:
            // второй случай ещё и указывает на сам каталог.
            clean = "file";
        }
        if (clean.length() > 120) {
            clean = clean.substring(0, 120);
        }
        return clean;
    }

    private static boolean isDotsOnly(String name) {
        for (int i = 0; i < name.length(); i++) {
            char c = name.charAt(i);
            if (c != '.' && c != '_') {
                return false;
            }
        }
        return true;
    }

    /**
     * Сколько байт получится после декодирования такой строки base64.
     *
     * Считаем по длине, без декодирования: смысл в том, чтобы отклонить
     * огромную строку ДО того, как под неё выделится память.
     */
    public static long estimatedBytes(String base64) {
        if (base64 == null || base64.isEmpty()) {
            return 0L;
        }
        long length = base64.length();
        long padding = 0;
        if (length >= 2 && base64.charAt((int) (length - 1)) == '=') {
            padding++;
        }
        if (length >= 3 && base64.charAt((int) (length - 2)) == '=') {
            padding++;
        }
        return (length / 4) * 3 - padding;
    }

    /**
     * Проверка перед записью. Возвращает текст ошибки или null, если всё в
     * порядке. Мост ничего не пишет, пока здесь нет ошибки.
     */
    public static String checkPayload(String base64) {
        return checkPayload(base64, MAX_BYTES);
    }

    /**
     * То же, но с заданным лимитом.
     *
     * Лимит вынесен в аргумент не для красоты: с константой внутри тест
     * лимита требовал бы строки на 44 млн символов (90 МБ) на каждый случай —
     * такая проверка жрёт память и валится от нехватки ресурсов вместо того,
     * чтобы сообщать о своей пользе. С маленьким лимитом (сотня байт) тест
     * проверяет ту же ветку кода мгновенно.
     */
    public static String checkPayload(String base64, int maxBytes) {
        if (base64 == null || base64.trim().isEmpty()) {
            return "страница прислала пустые данные";
        }
        // Считаем размер по длине строки, ничего не декодируя: estimatedBytes
        // читает только длину и два последних символа, то есть O(1) и без
        // единого байта памяти. Декодировать и потом проверять «не многовато ли»
        // поздно — память под результат к этому моменту уже выделена.
        long bytes = estimatedBytes(base64);
        if (bytes > maxBytes) {
            return "файл больше лимита " + humanSize(maxBytes)
                    + " (прислано " + humanSize(bytes) + ") — передайте его частями";
        }
        return null;
    }
}
